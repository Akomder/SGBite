"""Write sql/schema.sql (PostgreSQL DDL) from the mapped domain classes.

Run from the project root:  python scripts/export_schema.py
Used for report section 4.3.4 (SQL code).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app.domain.models import Base

out = ["-- SaigonBite OFDH schema (PostgreSQL). Generated by scripts/export_schema.py. Do not edit by hand.\n"]
for table in Base.metadata.sorted_tables:
    out.append(str(CreateTable(table).compile(dialect=postgresql.dialect())).strip() + ";\n")
    for index in table.indexes:
        out.append(str(CreateIndex(index).compile(dialect=postgresql.dialect())).strip() + ";\n")
target = Path(__file__).resolve().parent.parent / "sql" / "schema.sql"
target.write_text("\n".join(out), encoding="utf-8")
print("wrote", target)
